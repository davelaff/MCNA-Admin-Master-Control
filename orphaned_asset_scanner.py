def parse_dt(dt_str):
    if not dt_str:
        return None
    try:
        return datetime.datetime.fromisoformat(dt_str.replace("Z", "+00:00")).replace(tzinfo=None)
    except Exception:
        return None


def analyze_user(user, now):
    findings = []
    account_enabled = user.get("accountEnabled", True)
    licenses = user.get("assignedLicenses") or []
    mail = user.get("mail") or ""
    sign_in_activity = user.get("signInActivity") or {}
    last_signin_str = sign_in_activity.get("lastSignInDateTime") or ""
    created_str = (user.get("createdDateTime") or "")[:19]

    last_signin = parse_dt(last_signin_str)
    created = parse_dt(created_str)
    age_days = (now - created).days if created else None

    if not account_enabled:
        if licenses:
            findings.append((HIGH, f"Account disabled but has {len(licenses)} license(s) assigned — wasted spend"))
        if mail:
            findings.append((MEDIUM, "Account disabled with mail address — possible orphaned mailbox"))
    else:
        # Enabled account checks
        if last_signin is not None:
            days_since = (now - last_signin).days
            if days_since >= USER_STALE_DAYS:
                findings.append((MEDIUM, f"Enabled account, no sign-in in {days_since} days"))
        elif last_signin_str == "" and age_days is not None and age_days > USER_NEVER_SIGNIN_DAYS:
            findings.append((LOW, f"Enabled account created {age_days}d ago, never signed in"))

    return findings


