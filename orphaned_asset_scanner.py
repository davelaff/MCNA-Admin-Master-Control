def analyze_group(group, activity_map, now, token):
    findings = []
    owners = group.get("owners") or []
    created_str = (group.get("createdDateTime") or "")[:10]
    group_id = group["id"]

    try:
        created_dt = datetime.datetime.strptime(created_str, "%Y-%m-%d")
        age_days = (now - created_dt).days
    except Exception:
        age_days = None

    if is_m365_group(group):
        # No owners
        if not owners:
            findings.append((HIGH, "No owners assigned"))
        elif owners_all_disabled(group):
            findings.append((HIGH, "All owners have disabled accounts"))
        elif owner_count_disabled(group) > 0 and len(owners) == 1:
            findings.append((MEDIUM, "Single owner account is disabled"))

        # Activity check
        if activity_map is not None and age_days is not None and age_days > GROUP_INACTIVITY_DAYS:
            last_activity = activity_map.get(group_id)
            if not last_activity:
                findings.append((MEDIUM, f"No activity recorded in last {GROUP_INACTIVITY_DAYS} days (group age: {age_days}d)"))

        # Empty group (only check groups with other findings to limit API calls)
        if findings:
            count = fetch_group_member_count(token, group_id)
            if count is not None and count == 0:
                findings.append((MEDIUM, "No members"))

    elif is_distribution_or_mail_security(group):
        if not owners:
            findings.append((HIGH, "No owners assigned"))
        elif owners_all_disabled(group):
            findings.append((HIGH, "All owners have disabled accounts"))

        if age_days is not None and age_days > 365 and not findings:
            findings.append((LOW, f"Group age {age_days}d — verify still needed"))

    return findings


