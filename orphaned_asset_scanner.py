def main():
    now = datetime.datetime.now()
    today_str = now.strftime("%Y-%m-%d")
    now_str = now.strftime("%Y-%m-%d %H:%M")

    try:
        env = load_env(ENV_PATH)
    except FileNotFoundError:
        print(f"ERROR: .env not found at {ENV_PATH}")
        sys.exit(1)

    tenant_id = env["TENANT_ID"]
    client_id = env["CLIENT_ID"]
    user_email = env["USER_EMAIL"]

    print(f"Authenticating admin account ({user_email})...")
    try:
        token = get_token(
            tenant_id, client_id, ADMIN_SCOPES,
            ADMIN_TOKEN_CACHE, login_hint=user_email,
        )
    except Exception as e:
        msg = f"Admin auth failed: {e}"
        print(f"ERROR: {msg}")
        append_activity_log(f"{now_str} - Orphaned asset scan - FAILED - {msg}")
        sys.exit(1)

    print("Authenticated. Fetching groups...")
    try:
        all_groups = fetch_groups(token)
        print(f"  {len(all_groups)} groups total")
    except RuntimeError as e:
        msg = str(e)
        print(f"ERROR: {msg}")
        append_activity_log(f"{now_str} - Orphaned asset scan - FAILED - {msg}")
        sys.exit(1)

    print("Fetching users...")
    try:
        all_users = fetch_users(token)
        signin_available = any("signInActivity" in u for u in all_users)
        print(f"  {len(all_users)} users")
        if not signin_available:
            print("  NOTE: signInActivity not present in user records — sign-in age checks will be limited")
    except RuntimeError as e:
        msg = str(e)
        print(f"ERROR: {msg}")
        append_activity_log(f"{now_str} - Orphaned asset scan - FAILED - {msg}")
        sys.exit(1)

    print("Fetching group activity report...")
    try:
        activity_map = fetch_group_activity_report(token)
        activity_available = activity_map is not None
    except RuntimeError as e:
        msg = str(e)
        print(f"ERROR: {msg}")
        append_activity_log(f"{now_str} - Orphaned asset scan - FAILED - {msg}")
        sys.exit(1)

    # Classify groups
    m365_groups = [g for g in all_groups if is_m365_group(g)]
    dl_groups = [g for g in all_groups if is_distribution_or_mail_security(g)]
    print(f"\n  M365 Groups/Teams: {len(m365_groups)}")
    print(f"  Distribution/mail-enabled security groups: {len(dl_groups)}")

    print(f"\nAnalyzing {len(m365_groups)} M365 groups / Teams...")
    m365_results = []
    for group in sorted(m365_groups, key=lambda g: g.get("displayName", "").lower()):
        findings = analyze_group(group, activity_map, now, token)
        m365_results.append((group, findings))

    print(f"Analyzing {len(dl_groups)} distribution / mail-enabled security groups...")
    dl_results = []
    for group in sorted(dl_groups, key=lambda g: g.get("displayName", "").lower()):
        findings = analyze_group(group, activity_map, now, token)
        dl_results.append((group, findings))

    print(f"Analyzing {len(all_users)} users...")
    active_user_upns = build_active_user_set(all_users)
    user_results = []
    for user in sorted(all_users, key=lambda u: u.get("userPrincipalName", "").lower()):
        findings = analyze_user(user, now)
        user_results.append((user, findings))

    # Planner: authenticate as app, fetch plans for flagged M365 groups only
    cert_thumbprint = env.get("CERT_THUMBPRINT", "")
    cert_pfx_path = env.get("CERT_PFX_PATH", "")
    group_plans = {}
    if cert_thumbprint and cert_pfx_path:
        print("Acquiring app token for Planner (Tasks.Read.All)...")
        try:
            app_token = get_app_token(tenant_id, client_id, cert_thumbprint, cert_pfx_path)
            flagged_group_ids = [g["id"] for g, f in m365_results if f]
            print(f"  Fetching Planner plans for {len(flagged_group_ids)} flagged groups...")
            plan_total = 0
            for group_id in flagged_group_ids:
                plans = fetch_planner_plans_for_group(app_token, group_id)
                if plans:
                    group_plans[group_id] = [p.get("title") or "(untitled)" for p in plans]
                    plan_total += len(plans)
            print(f"  {plan_total} Planner plan(s) found in flagged groups")
        except RuntimeError as e:
            msg = str(e)
            print(f"  WARNING: Planner scan skipped — {msg}")
    else:
        print("CERT_THUMBPRINT or CERT_PFX_PATH not set in .env — skipping Planner scan")

    print("Fetching SharePoint sites...")
    try:
        all_sites = fetch_sharepoint_sites(token)
        sp_available = True
    except RuntimeError as e:
        msg = str(e)
        print(f"ERROR: {msg}")
        append_activity_log(f"{now_str} - Orphaned asset scan - FAILED - {msg}")
        sys.exit(1)

    print("Fetching SharePoint site usage report...")
    try:
        sp_usage_map = fetch_sharepoint_usage_report(token)
    except RuntimeError as e:
        msg = str(e)
        print(f"ERROR: {msg}")
        append_activity_log(f"{now_str} - Orphaned asset scan - FAILED - {msg}")
        sys.exit(1)

    print(f"Analyzing {len(all_sites)} SharePoint sites...")
    sp_results = []
    for site in sorted(all_sites, key=lambda s: (s.get("displayName") or "").lower()):
        usage, findings = analyze_sharepoint_site(site, sp_usage_map, active_user_upns, now)
        sp_results.append((site, findings, usage))

    # Write outputs
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    md_path = REPORTS_DIR / f"{today_str}.md"
    csv_path = REPORTS_DIR / f"{today_str}.csv"

    md_content = build_markdown(
        m365_results, dl_results, user_results, sp_results,
        today_str, now_str, tenant_id,
        activity_available=activity_available,
        signin_available=signin_available,
        sp_available=sp_available,
        group_plans=group_plans,
    )
    md_path.write_text(md_content, encoding="utf-8")
    print(f"\nWrote: {md_path}")

    csv_rows = build_csv_rows(m365_results, dl_results, user_results, sp_results)
    fieldnames = [
        "Type", "Display Name", "ID/Email", "Owners", "Created",
        "Last Activity", "Max Severity", "Findings", "Recommended Action",
    ]
    with open(csv_path, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(csv_rows)
    print(f"Wrote: {csv_path}")

    # sp_results is (site, findings, usage) triples; normalize to (obj, findings) for counting
    def iter_findings(*result_lists):
        for results in result_lists:
            for row in results:
                yield row[1]  # findings is always index 1

    high_count = sum(1 for f in iter_findings(m365_results, dl_results, user_results, sp_results) if any(s == HIGH for s, _ in f))
    medium_count = sum(1 for f in iter_findings(m365_results, dl_results, user_results, sp_results) if any(s == MEDIUM for s, _ in f))
    low_count = sum(1 for f in iter_findings(m365_results, dl_results, user_results, sp_results) if any(s == LOW for s, _ in f))
    total_flagged = sum(1 for f in iter_findings(m365_results, dl_results, user_results, sp_results) if f)

    outcome = (
        f"{total_flagged} assets flagged (High: {high_count}, Medium: {medium_count}, Low: {low_count})"
    )
    print(f"\n{outcome}")
    append_activity_log(
        f"{now_str} - Orphaned asset scan - {outcome}"
        f" - reports/orphaned-assets/{today_str}.md"
    )


if __name__ == "__main__":
    main()
