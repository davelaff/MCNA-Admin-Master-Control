def owner_str(group):
    owners = group.get("owners") or []
    if not owners:
        return "NONE"
    parts = []
    for o in owners:
        upn = o.get("userPrincipalName") or o.get("displayName", "?")
        enabled = o.get("accountEnabled")
        status = "" if enabled else " [DISABLED]"
        parts.append(f"{upn}{status}")
    return ", ".join(parts)


def user_owner_str(user):
    return user.get("userPrincipalName") or user.get("displayName", "?")


def last_activity_str(group_id, activity_map):
    if activity_map is None:
        return "N/A"
    val = activity_map.get(group_id)
    return val or "None recorded"


def max_severity(findings):
    if not findings:
        return "Clean"
    return min(findings, key=lambda f: SEVERITY_ORDER.get(f[0], 99))[0]


