def build_csv_rows(m365_results, dl_results, user_results, sp_results):
    rows = []

    for group, findings in m365_results:
        if not findings:
            continue
        rows.append({
            "Type": "M365 Group/Team",
            "Display Name": group.get("displayName", ""),
            "ID/Email": group.get("mail") or group.get("id", ""),
            "Owners": owner_str(group),
            "Created": (group.get("createdDateTime") or "")[:10],
            "Last Activity": "",
            "Max Severity": max_severity(findings),
            "Findings": "; ".join(f"[{s}] {d}" for s, d in findings),
            "Recommended Action": "Review and reassign owner or delete group",
        })

    for group, findings in dl_results:
        if not findings:
            continue
        rows.append({
            "Type": "Distribution Group",
            "Display Name": group.get("displayName", ""),
            "ID/Email": group.get("mail") or group.get("id", ""),
            "Owners": owner_str(group),
            "Created": (group.get("createdDateTime") or "")[:10],
            "Last Activity": "",
            "Max Severity": max_severity(findings),
            "Findings": "; ".join(f"[{s}] {d}" for s, d in findings),
            "Recommended Action": "Assign active owner or delete group",
        })

    for user, findings in user_results:
        if not findings:
            continue
        recommended = ""
        finding_texts = [d for _, d in findings]
        if any("license" in d for d in finding_texts):
            recommended = "Remove unneeded license(s) from disabled account"
        elif any("mailbox" in d for d in finding_texts):
            recommended = "Verify mailbox still needed; remove or convert to shared"
        elif any("no sign-in" in d for d in finding_texts):
            recommended = "Verify account still needed; disable or delete if stale"
        else:
            recommended = "Review account status"

        rows.append({
            "Type": "User Account",
            "Display Name": user.get("displayName", ""),
            "ID/Email": user.get("userPrincipalName", ""),
            "Owners": "",
            "Created": (user.get("createdDateTime") or "")[:10],
            "Last Activity": (user.get("signInActivity") or {}).get("lastSignInDateTime", "")[:10],
            "Max Severity": max_severity(findings),
            "Findings": "; ".join(f"[{s}] {d}" for s, d in findings),
            "Recommended Action": recommended,
        })

    for site, findings, usage in sp_results:
        if not findings:
            continue
        rows.append({
            "Type": "SharePoint Site",
            "Display Name": site.get("displayName") or site.get("name") or "",
            "ID/Email": site.get("webUrl") or "",
            "Owners": (usage or {}).get("owner_upn") or "",
            "Created": (site.get("createdDateTime") or "")[:10],
            "Last Activity": (usage or {}).get("last_activity") or "",
            "Max Severity": max_severity(findings),
            "Findings": "; ".join(f"[{s}] {d}" for s, d in findings),
            "Recommended Action": "Review site owner and activity; reassign or archive",
        })

    rows.sort(key=lambda r: (SEVERITY_ORDER.get(r["Max Severity"], 99), r["Display Name"].lower()))
    return rows


