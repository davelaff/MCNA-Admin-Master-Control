def graph_get(token, url, params=None, headers_extra=None):
    headers = {"Authorization": f"Bearer {token}"}
    if headers_extra:
        headers.update(headers_extra)
    resp = requests.get(url, headers=headers, params=params)
    if resp.status_code in (401, 403):
        raise RuntimeError(f"Graph auth error {resp.status_code}: {resp.text}")
    resp.raise_for_status()
    return resp


def get_all_pages(token, url, params=None, headers_extra=None):
    items = []
    resp = graph_get(token, url, params, headers_extra)
    data = resp.json()
    items.extend(data.get("value", []))
    while "@odata.nextLink" in data:
        resp = graph_get(token, data["@odata.nextLink"], headers_extra=headers_extra)
        data = resp.json()
        items.extend(data.get("value", []))
    return items


