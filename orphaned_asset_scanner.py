def is_m365_group(group):
    return "Unified" in (group.get("groupTypes") or [])


def is_distribution_or_mail_security(group):
    return (
        group.get("mailEnabled")
        and not is_m365_group(group)
    )


def owners_all_disabled(group):
    owners = group.get("owners") or []
    if not owners:
        return False
    return all(o.get("accountEnabled") is False for o in owners)


def owner_count_disabled(group):
    owners = group.get("owners") or []
    return sum(1 for o in owners if o.get("accountEnabled") is False)


