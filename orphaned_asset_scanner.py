def get_token(tenant_id, client_id, scopes, cache_path, login_hint=None):
    cache = msal.SerializableTokenCache()
    if cache_path.exists():
        cache.deserialize(cache_path.read_text())

    app = msal.PublicClientApplication(
        client_id=client_id,
        authority=f"https://login.microsoftonline.com/{tenant_id}",
        token_cache=cache,
    )

    accounts = app.get_accounts(username=login_hint)
    result = None
    if accounts:
        result = app.acquire_token_silent(scopes, account=accounts[0])

    if not result:
        flow = app.initiate_device_flow(scopes=scopes)
        if "user_code" not in flow:
            raise RuntimeError(f"Device flow failed: {flow}")
        print("\n" + flow["message"])
        print("Waiting for authentication...\n")
        result = app.acquire_token_by_device_flow(flow)

    if "access_token" not in result:
        raise RuntimeError(f"Auth failed: {result.get('error_description', result)}")

    if cache.has_state_changed:
        cache_path.write_text(cache.serialize())

    return result["access_token"]


def get_app_token(tenant_id, client_id, thumbprint, pfx_path):
    """
    Authenticate as the application using a PFX certificate file.
    PFX must have no password (as generated by this project).
    Returns an access token scoped to Tasks.Read.All (via .default).
    """
    pfx_bytes = pathlib.Path(pfx_path).read_bytes()
    try:
        private_key, _, _ = pkcs12.load_key_and_certificates(pfx_bytes, None)
    except Exception:
        private_key, _, _ = pkcs12.load_key_and_certificates(pfx_bytes, b"")

    private_key_pem = private_key.private_bytes(
        encoding=crypto_serialization.Encoding.PEM,
        format=crypto_serialization.PrivateFormat.TraditionalOpenSSL,
        encryption_algorithm=crypto_serialization.NoEncryption(),
    )

    app = msal.ConfidentialClientApplication(
        client_id,
        authority=f"https://login.microsoftonline.com/{tenant_id}",
        client_credential={"thumbprint": thumbprint, "private_key": private_key_pem.decode()},
    )
    token_result = app.acquire_token_for_client(scopes=PLANNER_SCOPES)
    if "access_token" not in token_result:
        raise RuntimeError(f"App token failed: {token_result.get('error_description', token_result)}")
    return token_result["access_token"]


