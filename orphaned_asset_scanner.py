def build_markdown(
    m365_results, dl_results, user_results, sp_results,
    today_str, now_str, tenant_id,
    activity_available, signin_available,
    sp_available, group_plans,
):
    def count_sev(results, sev):
        return sum(1 for row in results if any(s == sev for s, _ in row[1]))

    def has_findings(row):
        return bool(row[1])

    all_results = (m365_results, dl_results, user_results, sp_results)
    total_flagged = sum(sum(1 for row in r if has_findings(row)) for r in all_results)
    high = sum(count_sev(r, HIGH) for r in all_results)
    medium = sum(count_sev(r, MEDIUM) for r in all_results)
    low = sum(count_sev(r, LOW) for r in all_results)

    lines = [
        f"# Orphaned Asset Scan — {today_str}",
        "",
        f"Generated: {now_str}  ",
        f"Tenant: {tenant_id}  ",
        "",
        "## Summary",
        "",
        f"- M365 Groups / Teams scanned: {len(m365_results)}",
        f"- Distribution / mail-enabled security groups scanned: {len(dl_results)}",
        f"- Users scanned: {len(user_results)}",
        f"- SharePoint sites scanned: {len(sp_results)}" + ("" if sp_available else " (unavailable — Sites.Read.All unavailable)"),
        f"- Assets flagged: {total_flagged} — High: {high} | Medium: {medium} | Low: {low}",
        "",
    ]

    if not activity_available:
        lines += ["**NOTE:** M365 group activity report unavailable — inactivity checks skipped.", ""]
    if not signin_available:
        lines += ["**NOTE:** signInActivity unavailable — user sign-in age checks skipped.", ""]
    if not sp_available:
        lines += ["**NOTE:** SharePoint site enumeration unavailable — SP section skipped.", ""]

    # M365 Groups section
    flagged_m365 = [(g, f) for g, f in m365_results if f]
    if flagged_m365:
        lines += ["## M365 Groups / Teams — Flagged", ""]
        for sev in (HIGH, MEDIUM, LOW):
            section = [(g, f) for g, f in flagged_m365 if any(s == sev for s, _ in f)]
            if not section:
                continue
            lines += [f"### {sev}", ""]
            for group, findings in sorted(section, key=lambda x: x[0].get("displayName", "").lower()):
                name = group.get("displayName", "(unnamed)")
                mail = group.get("mail") or ""
                created = (group.get("createdDateTime") or "")[:10]
                lines += [
                    f"**{name}**" + (f" ({mail})" if mail else ""),
                    f"- Created: {created}",
                    f"- Owners: {owner_str(group)}",
                    f"- Findings:",
                ]
                for s, desc in sorted(findings, key=lambda x: SEVERITY_ORDER.get(x[0], 99)):
                    lines += [f"  - **[{s}]** {desc}"]
                plans = group_plans.get(group["id"], [])
                if plans:
                    lines += [f"- Planner plans: {', '.join(plans)}"]
                lines += [""]

    # DL / mail-enabled security groups section
    flagged_dl = [(g, f) for g, f in dl_results if f]
    if flagged_dl:
        lines += ["## Distribution Groups / Mail-Enabled Security Groups — Flagged", ""]
        for sev in (HIGH, MEDIUM, LOW):
            section = [(g, f) for g, f in flagged_dl if any(s == sev for s, _ in f)]
            if not section:
                continue
            lines += [f"### {sev}", ""]
            for group, findings in sorted(section, key=lambda x: x[0].get("displayName", "").lower()):
                name = group.get("displayName", "(unnamed)")
                mail = group.get("mail") or ""
                created = (group.get("createdDateTime") or "")[:10]
                lines += [
                    f"**{name}**" + (f" ({mail})" if mail else ""),
                    f"- Created: {created}",
                    f"- Owners: {owner_str(group)}",
                    f"- Findings:",
                ]
                for s, desc in sorted(findings, key=lambda x: SEVERITY_ORDER.get(x[0], 99)):
                    lines += [f"  - **[{s}]** {desc}"]
                lines += [""]

    # User accounts section
    flagged_users = [(u, f) for u, f in user_results if f]
    if flagged_users:
        lines += ["## User Accounts — Flagged", ""]
        for sev in (HIGH, MEDIUM, LOW):
            section = [(u, f) for u, f in flagged_users if any(s == sev for s, _ in f)]
            if not section:
                continue
            lines += [f"### {sev}", ""]
            for user, findings in sorted(section, key=lambda x: x[0].get("userPrincipalName", "").lower()):
                upn = user.get("userPrincipalName", "(unknown)")
                name = user.get("displayName", "")
                dept = user.get("department") or ""
                title = user.get("jobTitle") or ""
                created = (user.get("createdDateTime") or "")[:10]
                lines += [
                    f"**{upn}**" + (f" — {name}" if name else ""),
                ]
                if title or dept:
                    lines += [f"- Role: {title}" + (f", {dept}" if dept else "")]
                lines += [
                    f"- Created: {created}",
                    f"- Findings:",
                ]
                for s, desc in sorted(findings, key=lambda x: SEVERITY_ORDER.get(x[0], 99)):
                    lines += [f"  - **[{s}]** {desc}"]
                lines += [""]

    # SharePoint sites section
    flagged_sp = [(s, f, u) for s, f, u in sp_results if f]
    if sp_available:
        lines += ["## SharePoint Sites — Flagged", ""]
        if not flagged_sp:
            lines += [f"No issues found across {len(sp_results)} sites.", ""]
        else:
            for sev in (HIGH, MEDIUM, LOW):
                section = [(s, f, u) for s, f, u in flagged_sp if any(sv == sev for sv, _ in f)]
                if not section:
                    continue
                lines += [f"### {sev}", ""]
                for site, findings, usage in sorted(section, key=lambda x: (x[0].get("displayName") or "").lower()):
                    name = site.get("displayName") or site.get("name") or "(unnamed)"
                    url = site.get("webUrl") or ""
                    created = (site.get("createdDateTime") or "")[:10]
                    owner = (usage or {}).get("owner_upn") or ""
                    last_act = (usage or {}).get("last_activity") or ""
                    lines += [
                        f"**{name}**",
                        f"- URL: {url}",
                        f"- Created: {created}",
                    ]
                    if owner:
                        lines += [f"- Owner (report): {owner}"]
                    if last_act:
                        lines += [f"- Last activity: {last_act}"]
                    lines += ["- Findings:"]
                    for sv, desc in sorted(findings, key=lambda x: SEVERITY_ORDER.get(x[0], 99)):
                        lines += [f"  - **[{sv}]** {desc}"]
                    lines += [""]

    lines += [
        "---",
        f"mcna-tenant-intel orphaned_asset_scanner.py — {now_str}",
    ]
    return "\n".join(lines)


