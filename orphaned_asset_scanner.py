def fetch_sharepoint_sites(token):
    """
    Fetch all SharePoint sites tenant-wide via search=*.
    Returns list of site objects with id, displayName, webUrl, createdDateTime.
    """
    url = f"{GRAPH_V1}/sites"
    params = {
        "search": "*",
        "$select": "id,displayName,name,webUrl,createdDateTime,lastModifiedDateTime",
        "$top": 200,
    }
    try:
        sites = get_all_pages(token, url, params)
        # Filter out the root site (/sites/root) and OneDrive personal sites
        sites = [
            s for s in sites
            if "/personal/" not in (s.get("webUrl") or "").lower()
        ]
        print(f"  {len(sites)} SharePoint sites (excluding personal OneDrive)")
        return sites
    except RuntimeError as e:
        if "403" in str(e) or "401" in str(e):
            raise
        print(f"  NOTE: SharePoint site enumeration failed ({e}) — skipping")
        return []


def fetch_sharepoint_usage_report(token):
    """
    Fetch SharePoint site usage detail (last 180 days).
    Returns dict: site-collection-guid -> {owner_upn, last_activity, storage_bytes, active_files}.
    Returns None if unavailable.

    Microsoft returns a BOM-prefixed CSV with Site URL always empty;
    Site Id (the site-collection GUID) is the only reliable key.
    """
    url = f"{GRAPH_V1}/reports/getSharePointSiteUsageDetail(period='D180')"
    try:
        resp = graph_get(token, url)
        # Decode with utf-8-sig to strip BOM; Site URL is always empty in this report
        text = resp.content.decode("utf-8-sig")
        reader = csv.DictReader(io.StringIO(text))
        usage = {}
        for row in reader:
            site_id = (row.get("Site Id") or "").strip().lower()
            if not site_id:
                continue
            usage[site_id] = {
                "owner_upn": (row.get("Owner Principal Name") or "").strip().lower(),
                "owner_display": (row.get("Owner Display Name") or "").strip(),
                "last_activity": (row.get("Last Activity Date") or "").strip(),
                "storage_bytes": row.get("Storage Used (Byte)", "0").strip(),
                "active_files": row.get("Active File Count", "0").strip(),
                "is_deleted": (row.get("Is Deleted") or "").strip().lower() == "true",
            }
        print(f"  {len(usage)} sites in SharePoint usage report")
        return usage
    except Exception as e:
        print(f"  NOTE: SharePoint usage report unavailable ({e}) — skipping activity checks")
        return None


def fetch_group_activity_report(token):
    """
    Fetch M365 group activity report (last 180 days).
    Returns dict: groupId -> lastActivityDate (str or None).
    Returns None if endpoint unavailable.
    """
    url = f"{GRAPH_V1}/reports/getOffice365GroupsActivityDetail(period='D180')"
    try:
        resp = graph_get(token, url)
        # Response is CSV text
        reader = csv.DictReader(io.StringIO(resp.text))
        activity = {}
        for row in reader:
            group_id = row.get("Group Id") or row.get("group Id") or ""
            last_activity = (
                row.get("Last Activity Date")
                or row.get("lastActivityDate")
                or ""
            ).strip()
            if group_id:
                activity[group_id] = last_activity or None
        print(f"  {len(activity)} groups in activity report")
        return activity
    except Exception as e:
        print(f"  NOTE: Group activity report unavailable ({e}) — skipping inactivity checks")
        return None


