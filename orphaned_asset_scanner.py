# Sites inactive longer than this (and old enough) are flagged
SP_INACTIVITY_DAYS = 180

# Minimum site age before we flag for inactivity (avoid flagging new empty sites)
SP_MIN_AGE_DAYS = 90


def _site_collection_guid(site):
    """
    Extract the site-collection GUID from a Graph site id.
    Graph site ids are 'hostname,site-collection-guid,web-guid'.
    Returns lowercased GUID string, or empty string if unparseable.
    """
    raw = site.get("id") or ""
    parts = raw.split(",")
    if len(parts) == 3:
        return parts[1].lower()
    return raw.lower()


def analyze_sharepoint_site(site, usage_map, active_user_upns, now):
    """
    Returns (usage_record, findings) for a site.
    usage_record may be None if site has no activity data.
    active_user_upns: set of lowercased UPNs for enabled Entra accounts.

    Lookup key: site-collection GUID (middle segment of Graph site id),
    matched against Site Id from the usage report.

    Group-connected sites (Teams) report their backing group email as owner;
    these are skipped for owner-orphan checks since the M365 groups section
    already covers them.
    """
    findings = []
    site_guid = _site_collection_guid(site)
    created_str = (site.get("createdDateTime") or "")[:10]

    try:
        created_dt = datetime.datetime.strptime(created_str, "%Y-%m-%d")
        age_days = (now - created_dt).days
    except Exception:
        age_days = None

    usage = (usage_map or {}).get(site_guid) if site_guid else None

    # Skip sites already marked deleted in the report
    if usage and usage.get("is_deleted"):
        return usage, []

    owner_upn = (usage.get("owner_upn") or "") if usage else ""
    last_activity = (usage.get("last_activity") or "") if usage else ""

    # Owner check — skip group-backed sites (owner is a group email, not a user UPN).
    # Group-connected sites use @mcna.onmicrosoft.com as the owner; those are
    # covered by the M365 groups section.
    if owner_upn and not owner_upn.endswith("@mcna.onmicrosoft.com"):
        if owner_upn not in active_user_upns:
            findings.append((HIGH, f"Site owner '{owner_upn}' not found in active Entra accounts (disabled or departed)"))

    # Inactivity check
    if usage_map is not None:
        if usage is None:
            # Site not in activity report → zero activity in last 180 days
            if age_days is not None and age_days > SP_MIN_AGE_DAYS:
                findings.append((MEDIUM, f"No activity in last {SP_INACTIVITY_DAYS} days (site age: {age_days}d)"))
        elif last_activity:
            try:
                last_dt = datetime.datetime.strptime(last_activity, "%Y-%m-%d")
                inactive_days = (now - last_dt).days
                if inactive_days >= SP_INACTIVITY_DAYS:
                    findings.append((MEDIUM, f"Last activity {inactive_days} days ago ({last_activity})"))
            except Exception:
                pass
        elif usage is not None and not last_activity:
            # In report but no last activity date → no activity recorded
            if age_days is not None and age_days > SP_MIN_AGE_DAYS:
                findings.append((MEDIUM, f"In activity report but no activity date recorded (site age: {age_days}d)"))

    return usage, findings


